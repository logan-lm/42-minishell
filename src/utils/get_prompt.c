char	*ft_get_prompt(void)
{
	static int id = -1;

	id++;
	id = id % 9;
	char *str;
	if (id == 0)
		str = "\001\033[1;31m\002Minishell>\001\033[0m\002";
	if (id == 1)
		str = "\001\033[1;32m\002Minishell>\001\033[0m\002";
	if (id == 2)
		str = "\001\033[1;33m\002Minishell>\001\033[0m\002";
	if (id == 3)
		str = "\001\033[1;34m\002Minishell>\001\033[0m\002";
	if (id == 4)
		str = "\001\033[1;35m\002Minishell>\001\033[0m\002";
	if (id == 5)
		str = "\001\033[1;36m\002Minishell>\001\033[0m\002";
	if (id == 6)
		str = "\001\033[1;37m\002Minishell>\001\033[0m\002";
	if (id == 7)
		str = "\001\033[38;5;208m\002Minishell>\001\033[0m\002";
	if (id == 8)
		str = "\001\033[38;5;206m\002Minishell>\001\033[0m\002";
	return (str);
}
